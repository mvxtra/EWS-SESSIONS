const express = require('express');
const http = require('http');
const { Server } = require('socket.io');
const fs = require('fs');
const path = require('path');
const NodeMediaServer = require('node-media-server');

const app = express();
const server = http.createServer(app);

const io = new Server(server, {
    cors: {
        origin: '*',
        methods: ['GET', 'POST']
    }
});

const PORT = Number(process.env.PORT || 3000);
const RTMP_PORT = Number(process.env.RTMP_PORT || 1935);
const NMS_HTTP_PORT = Number(process.env.NMS_HTTP_PORT || 8000);

const ROOT = __dirname;
const PUBLIC_DIR = path.join(ROOT, 'public');
const MEDIA_DIR = path.join(ROOT, 'media');
const HLS_DIR = path.join(MEDIA_DIR, 'hls');
const DATA_DIR = path.join(ROOT, 'data');
const USERS_FILE = path.join(DATA_DIR, 'users.json');

for (const dir of [PUBLIC_DIR, MEDIA_DIR, HLS_DIR, DATA_DIR]) {
    if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
    }
}

if (!fs.existsSync(USERS_FILE)) {
    fs.writeFileSync(USERS_FILE, '[]', 'utf8');
}

app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: true }));

/* =========================================
   USERS
========================================= */

function readUsers() {
    try {
        return JSON.parse(
            fs.readFileSync(USERS_FILE, 'utf8')
        );
    } catch {
        return [];
    }
}

function saveUsers(users) {
    fs.writeFileSync(
        USERS_FILE,
        JSON.stringify(users, null, 2),
        'utf8'
    );
}

/* =========================================
   STATIC
========================================= */

app.use(express.static(PUBLIC_DIR));

/*
   HLS files generated by the streaming server
   are also served by Express.
*/
app.use(
    '/hls',
    express.static(HLS_DIR, {
        setHeaders: (res, file) => {

            res.setHeader(
                'Access-Control-Allow-Origin',
                '*'
            );

            res.setHeader(
                'Cache-Control',
                'no-cache, no-store, must-revalidate'
            );

            if (file.endsWith('.m3u8')) {
                res.setHeader(
                    'Content-Type',
                    'application/vnd.apple.mpegurl'
                );
            }

            if (file.endsWith('.ts')) {
                res.setHeader(
                    'Content-Type',
                    'video/mp2t'
                );
            }
        }
    })
);

/* =========================================
   REGISTER
========================================= */

app.post('/api/register', (req, res) => {

    const username =
        String(req.body.username || '').trim();

    const password =
        String(req.body.password || '');

    if (username.length < 2) {
        return res.json({
            ok: false,
            message: 'Username is too short'
        });
    }

    if (password.length < 3) {
        return res.json({
            ok: false,
            message: 'Password is too short'
        });
    }

    const users = readUsers();

    const exists = users.some(
        user =>
            user.username.toLowerCase() ===
            username.toLowerCase()
    );

    if (exists) {
        return res.json({
            ok: false,
            message: 'Username already exists'
        });
    }

    users.push({
        username,
        password,
        createdAt: Date.now()
    });

    saveUsers(users);

    console.log(
        `[REGISTER] ${username}`
    );

    res.json({
        ok: true,
        username
    });
});

/* =========================================
   LOGIN
========================================= */

app.post('/api/login', (req, res) => {

    const username =
        String(req.body.username || '').trim();

    const password =
        String(req.body.password || '');

    const users = readUsers();

    const user = users.find(
        item =>
            item.username.toLowerCase() ===
            username.toLowerCase() &&
            item.password === password
    );

    if (!user) {
        return res.json({
            ok: false,
            message: 'Wrong username or password'
        });
    }

    console.log(
        `[LOGIN] ${user.username}`
    );

    res.json({
        ok: true,
        username: user.username
    });
});

