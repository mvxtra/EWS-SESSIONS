/* =========================================
   ONLINE USERS
========================================= */

const onlineUsers = new Map();

/* =========================================
   PLAYERS
========================================= */

const players = new Map();

function onlineList() {
    return Array.from(
        onlineUsers.values()
    );
}

function playerList() {
    return Array.from(
        players.values()
    );
}

function sendOnline() {
    io.emit(
        'online-users',
        onlineList()
    );
}

function sendPlayers() {
    io.emit(
        'players-state',
        playerList()
    );
}

/* =========================================
   SOCKET.IO
========================================= */

io.on('connection', socket => {

    console.log(
        `[SOCKET] ${socket.id}`
    );

    /* -------------------------------------
       JOIN
    ------------------------------------- */

    socket.on('join', data => {

        const username =
            String(
                data?.username || 'Guest'
            ).trim();

        const language =
            String(
                data?.language || 'en'
            ).trim();

        if (!username) return;

        socket.username = username;
        socket.language = language;

        onlineUsers.set(
            socket.id,
            {
                id: socket.id,
                username,
                language
            }
        );

        players.set(
            socket.id,
            {
                id: socket.id,
                username,
                x: 0,
                y: 0,
                z: 8,
                ry: 0,
                jumping: false
            }
        );

        socket.emit(
            'joined',
            {
                ok: true,
                username
            }
        );

        socket.emit(
            'players-state',
            playerList()
        );

        socket.broadcast.emit(
            'player-joined',
            {
                id: socket.id,
                username
            }
        );

        socket.broadcast.emit(
            'system-message',
            {
                text:
                    `${username} entered EWS SESSIONS`,
                ts: Date.now()
            }
        );

        sendOnline();
        sendPlayers();

        console.log(
            `[JOIN] ${username}`
        );
    });

    /* -------------------------------------
       REQUEST ONLINE
    ------------------------------------- */

    socket.on(
        'request-online',
        () => {

            socket.emit(
                'online-users',
                onlineList()
            );

            socket.emit(
                'players-state',
                playerList()
            );
        }
    );

    /* -------------------------------------
       PLAYER POSITION
    ------------------------------------- */

    socket.on(
        'player-move',
        data => {

            const player =
                players.get(socket.id);

            if (!player) return;

            const x = Number(data?.x);
            const y = Number(data?.y);
            const z = Number(data?.z);
            const ry = Number(data?.ry);

            if (
                !Number.isFinite(x) ||
                !Number.isFinite(y) ||
                !Number.isFinite(z)
            ) {
                return;
            }

            player.x = x;
            player.y = y;
            player.z = z;

            if (Number.isFinite(ry)) {
                player.ry = ry;
            }

            player.jumping =
                Boolean(data?.jumping);

            socket.broadcast.emit(
                'player-move',
                player
            );
        }
    );

    /* -------------------------------------
       CHAT
    ------------------------------------- */

    socket.on(
        'chat-message',
        data => {

            if (!socket.username) return;

            const text =
                String(
                    data?.text || ''
                ).trim();

            if (!text) return;

            if (text.length > 500) return;

            io.emit(
                'chat-message',
                {
                    user: socket.username,
                    username: socket.username,
                    text,
                    original: text,
                    ts: Date.now()
                }
            );
        }
    );

    /* -------------------------------------
       LANGUAGE
    ------------------------------------- */

    socket.on(
        'language-change',
        language => {

            const user =
                onlineUsers.get(
                    socket.id
                );

            if (!user) return;

            user.language =
                String(
                    language || 'en'
                );

            onlineUsers.set(
                socket.id,
                user
            );

            sendOnline();
        }
    );

    /* -------------------------------------
       DISCONNECT
    ------------------------------------- */

    socket.on(
        'disconnect',
        reason => {

            const user =
                onlineUsers.get(
                    socket.id
                );

            if (!user) return;

            console.log(
                `[OFFLINE] ${user.username} | ${reason}`
            );

            onlineUsers.delete(
                socket.id
            );

            players.delete(
                socket.id
            );

            socket.broadcast.emit(
                'player-left',
                {
                    id: socket.id
                }
            );

            socket.broadcast.emit(
                'system-message',
                {
                    text:
                        `${user.username} left EWS SESSIONS`,
                    ts: Date.now()
                }
            );

            sendOnline();
            sendPlayers();
        }
    );
});

/* =========================================
   NODE MEDIA SERVER
========================================= */

try {

    const nmsConfig = {

        rtmp: {
            port: RTMP_PORT,
            chunk_size: 60000,
            gop_cache: true,
            ping: 30,
            ping_timeout: 60
        },

        http: {
            port: NMS_HTTP_PORT,
            mediaroot: MEDIA_DIR,
            allow_origin: '*'
        },

        trans: {

            ffmpeg:
                process.env.FFMPEG_PATH ||
                'ffmpeg',

            tasks: [
                {
                    app: 'ews',

                    hls: true,

                    hlsFlags:
                        '[hls_time=2:hls_list_size=6:hls_flags=delete_segments]',

                    dash: false
                }
            ]
        }
    };

    const nms =
        new NodeMediaServer(
            nmsConfig
        );

    nms.run();

    console.log(
        `[NMS] RTMP ${RTMP_PORT}`
    );

    console.log(
        `[NMS] HLS ${NMS_HTTP_PORT}`
    );

} catch (error) {

    console.log(
        '[NMS]',
        error.message
    );

    console.log(
        '[NMS] Website continues without media server'
    );
}

